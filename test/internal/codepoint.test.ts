describe("codepoint ordering", () => {
  it("matches Python sorted() for the BMP/astral case", () => {
    // python3 -c 'print(sorted(["�","😀","z"]))' -> ['z', '�', '😀']
    const input = ["�", "😀", "z"];
    expect(sortCodePoints(input)).toEqual(["z", "�", "😀"]);
    expect([...input].sort()).toEqual(["z", "😀", "�"]); // the JS default is wrong
    expect(input).toEqual(["�", "😀", "z"]); // not mutated
  });

  it("prefix, equal and mixed astral comparisons", () => {
    expect(compareCodePoints("a", "a")).toBe(0);
    expect(compareCodePoints("a", "ab")).toBe(-1);
    expect(compareCodePoints("ab", "a")).toBe(1);
    expect(compareCodePoints("😀a", "😀b")).toBe(-1);
    expect(compareCodePoints("😀", "😁")).toBe(-1);
    expect(compareCodePoints("￿", "\u{10000}")).toBe(-1);
    expect(compareCodePoints("", "\u{10000}")).toBe(-1);
    expect(compareCodePoints("", "a")).toBe(-1);
  });

  it("sorts key-path style strings", () => {
    expect(sortCodePoints(["b.c", "a", "b", "b.[]", "B"])).toEqual(["B", "a", "b", "b.[]", "b.c"]);
  });

  // python3 -c 'print("\ud83d" < "\U0001F600")' -> True
  it("lone high surrogate sorts below the astral char it would start", () => {
    expect(compareCodePoints("\ud83d", "\u{1F600}")).toBe(-1);
    expect(compareCodePoints("\u{1F600}", "\ud83d")).toBe(1);
  });

  // python3 -c 'print("\ud83d\uffff" < "\U0001F600")' -> True
  it("lone surrogate followed by U+FFFF vs astral", () => {
    expect(compareCodePoints("\ud83d\uffff", "\u{1F600}")).toBe(-1);
    expect(compareCodePoints("\u{1F600}", "\ud83d\uffff")).toBe(1);
  });

  // python3: "\udc00" < "A" False; "\udc00" < "\ue000" True; "\udc00" > "\ud7ff" True
  it("lone low surrogate vs BMP characters", () => {
    expect(compareCodePoints("\udc00", "A")).toBe(1);
    expect(compareCodePoints("\udc00", "\ue000")).toBe(-1);
    expect(compareCodePoints("\udc00", "\ud7ff")).toBe(1);
  });

  it("matches a Python sorted() result for 200 random strings with lone surrogates", () => {
    expect(RANDOM_INPUT).toHaveLength(200);
    expect(sortCodePoints(RANDOM_INPUT)).toEqual(RANDOM_SORTED);
  });
});
